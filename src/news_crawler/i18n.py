def t(lang: str, key: str, **kwargs: str) -> str:
    """Look up a localized string; falls back to English."""
    text = STRINGS.get(lang, STRINGS["en"]).get(key, STRINGS["en"].get(key, key))
    if kwargs:
        return text.format(**kwargs)
    return text


def market_label(lang: str, market_id: str) -> str:
    return t(lang, f"market_{market_id}")


def language_label(lang: str, ui_lang: str) -> str:
    return t(lang, f"lang_{ui_lang}")
